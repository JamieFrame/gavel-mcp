#!/usr/bin/env node
/**
 * sync-testnet-instructions — VZ10 row M1, G4: the gavel-testnet profile's `initialize` instructions, generated
 * word for word from their single source, aletheia-docs commercial/operational/agent_listing_copy_v1.md §8.2.
 *
 *   node scripts/sync-testnet-instructions.mjs --docs <aletheia-docs> [--ref <ref>] [--check]
 *
 * --ref    read the copy pack at this ref with `git show` (recorded in the file); without it, the docs working
 *          tree is read and recorded as such (for drafting only: a committed ref is what is merged).
 * --check  regenerate in memory and compare with src/v2/instructions.generated.ts; exit 1 on any difference.
 *
 * §8.2's text is its blockquote: each `> ` line is a line of a paragraph, and `>` alone separates paragraphs.
 */
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const opt = (k) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : undefined; };
const DOCS = opt('--docs');
const REF = opt('--ref');
const CHECK = args.includes('--check');
const die = (m) => { console.error(`sync-testnet-instructions: ${m}`); process.exit(1); };
if (!DOCS) die('--docs <aletheia-docs> is required');

const PATH = 'commercial/operational/agent_listing_copy_v1.md';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const TARGET = join(ROOT, 'src/v2/instructions.generated.ts');

const md = REF
  ? execFileSync('git', ['-C', DOCS, 'show', `${REF}:${PATH}`], { encoding: 'utf8' })
  : readFileSync(join(DOCS, PATH), 'utf8');
const source = REF ? execFileSync('git', ['-C', DOCS, 'rev-parse', REF], { encoding: 'utf8' }).trim() : 'working tree';

const start = md.indexOf('### 8.2 ');
if (start < 0) die('§8.2 not found');
const lines = md.slice(start).split(/\r?\n/).slice(1);
const quote = [];
let begun = false;
for (const l of lines) {
  if (l.startsWith('>')) { begun = true; quote.push(l === '>' ? '' : l.replace(/^> /, '')); }
  else if (begun) break;
}
const paragraphs = quote.join('\n').split(/\n\n/).map((p) => p.replace(/\n/g, ' ').trim());
if (paragraphs.length < 4) die(`§8.2 has ${paragraphs.length} paragraphs; expected at least four`);
const text = paragraphs.join('\n\n');
const heading = md.slice(start, md.indexOf('\n', start));
const stated = heading.match(/— ([\d,]+) characters/);
if (stated && Number(stated[1].replace(/,/g, '')) !== text.length) die(`§8.2's heading states ${stated[1]} characters; the text is ${text.length}`);

const out =
  `// GENERATED by scripts/sync-testnet-instructions.mjs from aletheia-docs ${PATH} §8.2\n` +
  `// at ${source}. Do not edit; edit the copy pack and regenerate.\n` +
  `export const GAVEL_TESTNET_INSTRUCTIONS_SOURCE = ${JSON.stringify({ repository: 'aletheia-docs', path: PATH, section: '8.2', at: source })} as const;\n` +
  `export const GAVEL_TESTNET_INSTRUCTIONS = ${JSON.stringify(text)};\n`;

if (CHECK) {
  if (!existsSync(TARGET)) die('src/v2/instructions.generated.ts does not exist; run without --check');
  const cur = readFileSync(TARGET, 'utf8');
  const curText = cur.match(/export const GAVEL_TESTNET_INSTRUCTIONS = (".*");/)?.[1];
  if (!curText || JSON.parse(curText) !== text) die(`the profile's instructions differ from §8.2 at ${source}`);
  console.log(`gavel-testnet instructions match §8.2 at ${source} (${paragraphs.length} paragraphs, ${text.length} characters)`);
} else {
  writeFileSync(TARGET, out);
  console.log(`wrote src/v2/instructions.generated.ts: ${paragraphs.length} paragraphs, ${text.length} characters, from ${source}`);
}
