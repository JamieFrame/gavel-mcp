import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import type { Profile } from '../profiles.js';
import { BUILD_OUTLINES } from './build-outlines.generated.js';

/**
 * VZ10 row M1, G4 — the build-outlines resource (operator's ruling, G4; agent_listing_copy §8.2's fourth
 * paragraph).
 *
 * What can be composed from this profile's tools: for each of the testnet site's Build cards ("What a team
 * could launch"), the contracts, read tools and write tools the composition uses, and what is not yet served.
 * The cards — their order, titles, bodies and status — are the site's, generated by
 * scripts/sync-build-outlines.mjs; the tools and contracts per card are src/v2/build-outlines.map.ts.
 *
 * A resource, not a tool (the ruling). It describes; it ranks nothing and recommends nothing: the cards keep the
 * site's order, and no field scores, compares or prefers one. No rates, yields or "best use".
 *
 * GAVEL-TESTNET ONLY. The gavel and observatory profiles are unchanged; server.ts declares the resources
 * capability for this profile only when it has one registered.
 */
export const BUILD_OUTLINES_URI = 'gavel-testnet://build-outlines.json';

export function registerBuildOutlinesResource(server: McpServer, profile: Profile): void {
  if (profile.id !== 'gavel-testnet') return;
  server.registerResource(
    'build-outlines',
    BUILD_OUTLINES_URI,
    {
      title: 'Build outlines',
      description:
        "What can be composed from this server's tools: for each of the testnet site's Build cards, the contracts, read tools and write tools it uses, and what is not yet served. In the site's order; it describes, and ranks or recommends nothing.",
      mimeType: 'application/json',
    },
    async (uri) => ({
      contents: [
        {
          uri: uri.href,
          mimeType: 'application/json',
          text: JSON.stringify(
            {
              about:
                'Outlines of what a team could compose from Gavel V2 on Arbitrum Sepolia with this server: each names the contracts, the read tools and the write tools a composition uses, and what this server does not yet serve for it. Listed in the order of the testnet site\'s Build page; nothing here ranks them, prices them or recommends one. Test tokens with no value; unaudited contracts.',
              source: BUILD_OUTLINES.source,
              count: BUILD_OUTLINES.outlines.length,
              outlines: BUILD_OUTLINES.outlines,
            },
            null,
            2
          ),
        },
      ],
    })
  );
}
